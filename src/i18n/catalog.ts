function translate(value: string): string {
  const result = kkCatalogText[value];
  if (result === undefined) throw new Error(`Missing Kazakh catalogue translation: ${value}`);
  return result;
}

function optional(value: string | null): string | null {
  return value == null ? null : translate(value);
}

export function localizeCategory(category: Category, locale: Locale): Category {
  if (locale === "ru") return category;
  return { ...category, name: translate(category.name), short: translate(category.short) };
}

export function localizeProduct(product: Product, locale: Locale): Product {
  if (locale === "ru") return product;
  return {
    ...product,
    name: translate(product.name),
    shortDescription: translate(product.shortDescription),
    fullDescription: optional(product.fullDescription),
    weight: optional(product.weight),
    servings: optional(product.servings),
    ingredients: product.ingredients?.map(translate) ?? null,
    allergens: product.allergens?.map(translate) ?? null,
    shelfLife: optional(product.shelfLife),
    storage: optional(product.storage),
    variants: product.variants?.map((variant) => ({ ...variant, label: translate(variant.label) })),
  };
}

export function getCatalog(locale: Locale) {
  return {
    categories: categories.map((category) => localizeCategory(category, locale)),
    products: products.map((product) => localizeProduct(product, locale)),
  };
}
